int main() {
    try {
        FloatingPointMaskGuard floating_point_guard;
        Ort::InitApi();
        Ort::SessionOptions options;
        ConfigureSessionOptions(options, 1);
        Ort::Session session(Environment(), kModel, sizeof(kModel), options);
        std::array<uint8_t, 64> input{};
        for (size_t i = 0; i < 32; ++i) {
            input[i] = 255;
            input[i + 32] = (i % 2 == 0) ? 255 : 0;
        }
        const std::array<int64_t, 2> dimensions{2, 32};
        const auto memory = Ort::MemoryInfo::CreateCpu(
            OrtArenaAllocator, OrtMemTypeDefault);
        auto tensor = Ort::Value::CreateTensor<uint8_t>(memory, input.data(),
            input.size(), dimensions.data(), dimensions.size());
        const char* input_names[] = {"A"};
        const char* output_names[] = {"Y"};
        auto outputs = session.Run(Ort::RunOptions{nullptr}, input_names, &tensor,
            1, output_names, 1);
        const std::array<int32_t, 8> expected{
            1036320, -1044480, 514080, -522240,
            518160, -522240, 257040, -261120};
        if (outputs.size() != 1 ||
            outputs[0].GetTensorTypeAndShapeInfo().GetElementCount() != expected.size()) {
            throw std::runtime_error("invalid integer precision output shape");
        }
        const auto* actual = outputs[0].GetTensorData<int32_t>();
        for (size_t i = 0; i < expected.size(); ++i) {
            if (actual[i] != expected[i]) {
                std::cerr << "quantized product " << i << ": expected "
                          << expected[i] << ", got " << actual[i] << '\n';
                return 1;
            }
        }
        std::cout << "ort_quantized_integer_precision=passed\n";
        return 0;
    } catch (const std::exception& error) {
        std::cerr << error.what() << '\n';
        return 1;
    }
}
